# Datasets

Source data used in this project: Google Analytics 4 (GA4) E-Commerce Web Event Export Dataset.

## Source

[Google Analytics 4 E-Commerce Web Dataset](https://www.kaggle.com/) — real, anonymized web event tracking data capturing user interactions, session metadata, channel traffic dimensions, and conversion funnel activities.

